const dictionaries: Record<Language, Record<TranslationKey, string>> = {
  "en-us": enUS,
  "zh-cn": zhCN,
};

let activeLanguage: Language = DEFAULT_LANGUAGE;

export function configureI18n(language: Language): void {
  activeLanguage = isLanguage(language) ? language : DEFAULT_LANGUAGE;
}

export function getLanguage(): Language {
  return activeLanguage;
}

export function translate(
  language: Language,
  key: TranslationKey,
  params?: Record<string, string | number | undefined>,
): string {
  const template = dictionaries[language][key] ?? enUS[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name];
    return value === undefined ? match : String(value);
  });
}

export function t(key: TranslationKey, params?: Record<string, string | number | undefined>): string {
  return translate(activeLanguage, key, params);
}

